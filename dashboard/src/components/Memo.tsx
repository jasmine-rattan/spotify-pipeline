import React, { useEffect, useState } from 'react'
import ReactMarkdown from 'react-markdown'

export default function Memo() {
  const [memo, setMemo] = useState<string>('')
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    fetch('/api/recommendations')
      .then(r => r.json())
      .then(d => { setMemo(d.memo || ''); setLoading(false) })
      .catch(() => setLoading(false))
  }, [])

  if (loading) return <p>Loading memo...</p>
  if (!memo) return <p>Memo not yet generated. Run Stage 6 first.</p>

  return (
    <div style={{ maxWidth: 800 }}>
      <h2>AI Product Memo</h2>
      <p style={{ color: '#666', fontSize: 13 }}>
        Generated by Claude Haiku based on analysis of 660,622 Spotify app reviews.
        Claim IDs (e.g. claim-001) reference exact numbers in claims.csv.
      </p>
      <div style={{
        background: '#f8f8f8',
        borderRadius: 8,
        padding: '20px 28px',
        lineHeight: 1.7,
      }}>
        <ReactMarkdown>{memo}</ReactMarkdown>
      </div>
    </div>
  )
}
